#!/usr/bin/env bash
# Regenerate the SRDF self-collision matrix for the Inspector.
#
# Run whenever link geometry changes (task 2.4 adds the flange and sensor
# bodies to s3_tool0). Needs this workspace built and sourced.
#
#   src/motobat_hc10dt_moveit_config/scripts/regen_collision_matrix.sh
#
# collisions_updater samples random joint states and disables a link pair only
# if it is adjacent or never collides in any sample. It rewrites the SRDF and
# drops comments, so it runs on a copy and only the disable_collisions lines
# are merged back. "default" (pairs touching at all-zeros) is deliberately not
# used: none touch on the HC10DT today, and if a future tool does, that is a
# collision to see, not to hide.
set -eo pipefail

PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRDF="${PKG}/config/motobat_inspector.srdf"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

xacro "${PKG}/config/motobat_inspector.urdf.xacro" > "${TMP}/robot.urdf"
(cd "${TMP}" && ros2 run moveit_setup_assistant collisions_updater \
    --urdf "${TMP}/robot.urdf" --srdf "${SRDF}" --output "${TMP}/out.srdf" \
    --always --trials 100000 > "${TMP}/log" 2>&1) || { cat "${TMP}/log"; exit 1; }

/usr/bin/python3 - "${TMP}/out.srdf" "${SRDF}" <<'PY'
import sys
gen, path = sys.argv[1], sys.argv[2]
pairs = [l.strip() for l in open(gen) if '<disable_collisions' in l]
s = open(path).read()
marker = '  <!-- Generated by collisions_updater (see header). Do not hand-edit. -->\n'
head = s[:s.index('</robot>')]
if marker in head:
    head = head[:head.index(marker)]
s = head.rstrip() + '\n\n' + marker + ''.join(f'  {p}\n' for p in pairs) + '</robot>\n'
open(path, 'w').write(s)
print(f'{len(pairs)} disabled pairs written to {path}')
PY

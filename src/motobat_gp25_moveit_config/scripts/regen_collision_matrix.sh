#!/usr/bin/env bash
# Regenerate the SRDF self-collision matrix for Station 4b (GP25).
#
# Run whenever link geometry changes (the gripper, fixtures and magazines are links too).
# Needs this workspace built and sourced.
#
#   src/motobat_gp25_moveit_config/scripts/regen_collision_matrix.sh
#
# collisions_updater samples random joint states and disables a link pair only
# if it is adjacent or never collides in any sample. It rewrites the SRDF and
# drops comments, so it runs on a copy and only the disable_collisions lines
# are merged back. "default" (pairs touching at all-zeros) is deliberately not
# used: none touch on the GP25 at all-zeros, and if a future tool does, that is a
# collision to see, not to hide.
#
# Unlike the Inspector, this station's URDF carries its fixtures (conveyor, pedestal, laser enclosure walls
# magazines). A robot-fixture pair is NOT disabled for "Never" colliding in random samples:
# a rarely reachable fixture would silently drop out of collision checking. Robot-fixture
# pairs are disabled only when Adjacent or Always in contact (the base on its pedestal);
# "Never" is kept for robot-robot and fixture-fixture pairs.
set -eo pipefail

PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRDF="${PKG}/config/motobat_welder.srdf"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

xacro "${PKG}/config/motobat_welder.urdf.xacro" > "${TMP}/robot.urdf"
(cd "${TMP}" && ros2 run moveit_setup_assistant collisions_updater \
    --urdf "${TMP}/robot.urdf" --srdf "${SRDF}" --output "${TMP}/out.srdf" \
    --always --trials 100000 > "${TMP}/log" 2>&1) || { cat "${TMP}/log"; exit 1; }

/usr/bin/python3 - "${TMP}/out.srdf" "${SRDF}" "${TMP}/robot.urdf" <<'PY'
import re, sys
import xml.etree.ElementTree as ET
gen, path, urdf = sys.argv[1], sys.argv[2], sys.argv[3]
fixtures = {j.find('child').get('link') for j in ET.parse(urdf).getroot().iter('joint')
            if j.get('name').startswith('world-')}
pairs, dropped = [], 0
for l in open(gen):
    if '<disable_collisions' not in l:
        continue
    a, b, why = re.search(r'link1="([^"]+)" link2="([^"]+)" reason="([^"]+)"', l).groups()
    if ((a in fixtures) != (b in fixtures)) and why not in ('Adjacent', 'Always'):
        dropped += 1
        continue
    pairs.append(l.strip())
print(f'{dropped} robot-fixture "Never" pairs kept in collision checking')
s = open(path).read()
marker = '  <!-- Generated by collisions_updater (see header). Do not hand-edit. -->\n'
head = s[:s.index('</robot>')]
if marker in head:
    head = head[:head.index(marker)]
s = head.rstrip() + '\n\n' + marker + ''.join(f'  {p}\n' for p in pairs) + '</robot>\n'
open(path, 'w').write(s)
print(f'{len(pairs)} disabled pairs written to {path}')
PY

#!/usr/bin/python3
"""
Mass properties for the HC10DT links, from the vendor collision meshes. (task 2.2)

The vendor URDF (motoman_hc10_support) has no <inertial> tags. RViz and MoveIt
don't need them; Gazebo does, and it drops a massless link. Yaskawa publishes
only the robot's total mass, so this script:

  1. reads each link's collision STL (binary, metres, link frame)
  2. computes its volume, centre of mass and inertia tensor about the centre
     of mass exactly, by summing signed tetrahedra (divergence theorem)
  3. assumes ONE uniform density for the whole arm, chosen so the links sum to
     the published mass

Tags: total mass S (Yaskawa EU product page, HC10DT: 48 kg; the IP67 variant is
58 kg). Uniform density A, so the split of mass between links is an estimate:
motors and gearboxes put real mass nearer the joints. Good enough for a
simulation whose joints are position-commanded; not for dynamics
identification or effort-based collision detection.

    hc10dt_inertials.py > ../config/hc10dt_inertials.yaml
"""
import struct
import sys
from pathlib import Path

import numpy as np

TOTAL_MASS = 48.0  # kg, S
MESHES = {
    'base_link': 'hc10/collision/base_link.stl',
    'link_1_s': 'hc10/collision/link_1_s.stl',
    'link_2_l': 'hc10/collision/link_2_l.stl',
    'link_3_u': 'hc10/collision/link_3_u.stl',
    'link_4_r': 'hc10/collision/link_4_r.stl',
    'link_5_b': 'hc10/collision/link_5_b.stl',
    'link_6_t': 'hc10dt/collision/link_6_t.stl',   # the DT tool flange
}


def read_stl(path):
    data = Path(path).read_bytes()
    n = struct.unpack_from('<I', data, 80)[0]
    if len(data) != 84 + 50 * n:
        sys.exit(f'{path}: not a binary STL')
    rec = np.frombuffer(data, dtype=np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')]),
                        count=n, offset=84)
    return rec['v'].astype(np.float64)          # (n, 3 vertices, xyz)


def mass_properties(tris):
    """Volume, centroid and inertia tensor (about the centroid, unit density)
    of a closed triangle mesh. Tonon (2004) / Eberly's polyhedral mass properties."""
    a, b, c = tris[:, 0], tris[:, 1], tris[:, 2]
    d = np.einsum('ij,ij->i', a, np.cross(b, c))           # 6 * signed tet volume
    vol = d.sum() / 6.0
    com = (d[:, None] * (a + b + c)).sum(0) / (24.0 * vol)
    # second moments  integral of x_i x_j dV  over each tetrahedron (origin, a, b, c)
    s = a + b + c
    P = np.zeros((3, 3))
    for i in range(3):
        for j in range(3):
            P[i, j] = (d * (a[:, i] * a[:, j] + b[:, i] * b[:, j] + c[:, i] * c[:, j]
                            + s[:, i] * s[:, j])).sum() / 120.0
    I_origin = np.trace(P) * np.eye(3) - P                    # inertia about the origin
    I_com = I_origin - vol * (np.dot(com, com) * np.eye(3) - np.outer(com, com))
    return vol, com, I_com


def main():
    share = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if share is None:
        from ament_index_python.packages import get_package_share_directory
        share = Path(get_package_share_directory('motoman_hc10_support'))
    props = {k: mass_properties(read_stl(share / 'meshes' / p)) for k, p in MESHES.items()}
    if any(v <= 0 for v, _, _ in props.values()):
        sys.exit('a mesh has non-positive volume: not closed, or inverted normals')
    rho = TOTAL_MASS / sum(v for v, _, _ in props.values())

    print('# GENERATED by motobat_description/scripts/hc10dt_inertials.py. Do not hand-edit.')
    print(f'# Total mass {TOTAL_MASS} kg (S, Yaskawa HC10DT), uniform density '
          f'{rho:.0f} kg/m^3 (A) over the vendor collision meshes.')
    print('# Inertia about the centre of mass, in the link frame, kg m^2.')
    print('hc10dt_inertials:')
    for k, (v, com, I) in props.items():
        I = I * rho
        ev = np.linalg.eigvalsh(I)
        assert ev.min() > 0 and ev[0] + ev[1] >= ev[2] - 1e-12, f'{k}: not a physical inertia'
        print(f'  {k}:  # volume {v * 1e3:.3f} L')
        print(f'    mass: {v * rho:.4f}')
        print(f'    xyz: [{com[0]:.5f}, {com[1]:.5f}, {com[2]:.5f}]')
        print(f'    ixx: {I[0, 0]:.6f}')
        print(f'    ixy: {I[0, 1]:.6f}')
        print(f'    ixz: {I[0, 2]:.6f}')
        print(f'    iyy: {I[1, 1]:.6f}')
        print(f'    iyz: {I[1, 2]:.6f}')
        print(f'    izz: {I[2, 2]:.6f}')


if __name__ == '__main__':
    main()
